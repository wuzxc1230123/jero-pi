#!/usr/bin/env node

import { readFile, mkdir, writeFile } from "node:fs/promises";
import { stripTypeScriptTypes } from "node:module";
import { dirname, join, posix } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
// Runtime module name → lib source after the domain restructure.
const sources = [
	{ name: "gentle-ai-binary", lib: "lib/core/gentle-ai-binary.ts" },
	{ name: "review-relay-contract", lib: "lib/review/review-relay-contract.ts" },
	{ name: "review-integration-v2", lib: "lib/review/review-integration-v2.ts" },
	{ name: "review-risk-assessment", lib: "lib/review/review-risk-assessment.ts" },
	{ name: "native-review-cli", lib: "lib/native/native-review-cli.ts" },
	{ name: "telemetry-trigger", lib: "lib/core/telemetry-trigger.ts" },
];
const header = "// Generated by scripts/build-runtime-modules.mjs. Do not edit.\n";
// Sources now live in lib domain subdirectories but runtime/ stays flat: imports
// between runtime sources become sibling ./name.mjs references, and climbs out
// of lib/<domain>/ lose one ../ level to keep matching the flat output layout.
const sourceByName = new Map(sources.map((source) => [source.lib, source.name]));
const relativeImportRe = /((?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)["'])(\.{1,2}\/[^"']+)(["'])/g;

function flattenRuntimeImports(javascript, libPath) {
	const sourceDir = posix.dirname(libPath);
	return javascript.replace(relativeImportRe, (match, prefix, spec, suffix) => {
		const resolved = posix.normalize(posix.join(sourceDir, spec));
		const runtimeSibling = sourceByName.get(resolved);
		if (runtimeSibling) return `${prefix}./${runtimeSibling}.mjs${suffix}`;
		if (spec.startsWith("../../")) return `${prefix}${spec.slice(3)}${suffix}`;
		return match;
	});
}

function assertNoTrailingWhitespace(content, label) {
	const line = content.split("\n").findIndex((value) => /[ \t]+$/.test(value));
	if (line >= 0) throw new Error(`${label} contains trailing whitespace on line ${line + 1}`);
}

async function generatedBytes(name, libPath) {
	const source = await readFile(join(root, libPath), "utf8");
	assertNoTrailingWhitespace(source, libPath);
	const javascript = flattenRuntimeImports(stripTypeScriptTypes(source, { mode: "strip" }), libPath)
		.replace(/\.ts(["'])/g, ".mjs$1")
		.replace(/[ \t]+$/gm, "")
		.replace(/\s+$/u, "");
	const generated = `${header}${javascript}\n`;
	assertNoTrailingWhitespace(generated, `runtime/${name}.mjs`);
	return generated;
}

async function main() {
	const mode = process.argv[2];
	if ((mode !== "--write" && mode !== "--check") || process.argv.length !== 3) {
		throw new Error("usage: build-runtime-modules.mjs --write|--check");
	}
	// Pi loads these directly as TypeScript. Check syntax without generating
	// another runtime copy or expanding the published module boundary.
	for (const path of ["lib/metrics/runtime-metrics-delivery.ts", "lib/metrics/runtime-metrics-native.ts",
		"lib/metrics/runtime-metrics-children.ts", "extensions/runtime-metrics.ts"]) {
		const source = await readFile(join(root, path), "utf8");
		assertNoTrailingWhitespace(source, path);
		stripTypeScriptTypes(source, { mode: "strip" });
	}
	const runtime = join(root, "runtime");
	if (mode === "--write") await mkdir(runtime, { recursive: true });
	const drift = [];
	for (const { name, lib } of sources) {
		const destination = join(runtime, `${name}.mjs`);
		const expected = await generatedBytes(name, lib);
		if (mode === "--write") {
			await writeFile(destination, expected, "utf8");
			continue;
		}
		let actual;
		try {
			actual = await readFile(destination, "utf8");
		} catch {
			actual = undefined;
		}
		if (actual !== expected) drift.push(destination);
	}
	if (drift.length > 0) {
		throw new Error(`generated runtime is stale: ${drift.join(", ")}`);
	}
	process.stdout.write(`runtime ${mode === "--write" ? "generated" : "matches TypeScript sources"} (${sources.length} generated modules; one-shot metrics sources validated)\n`);
}

main().catch((error) => {
	process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
	process.exitCode = 1;
});
