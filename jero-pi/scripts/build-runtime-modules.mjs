#!/usr/bin/env node

import { existsSync } from "node:fs";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { stripTypeScriptTypes } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const sources = [
	"authority/wire-contract",
	"authority/wire-contract-enums",
	"authority/wire-contract-interfaces",
	"authority/wire-contract-decode-helpers",
	"authority/wire-contract-decode-start",
	"authority/wire-contract-decode-status",
	"authority/wire-contract-last-event",
	"review-risk-assessment",
	"record-utils",
	"authority/client-contract",
	"authority/client-contract-types",
	"authority/client-contract-surface",
	"authority/client-contract-decode",
];
const header = "// Generated by scripts/build-runtime-modules.mjs. Do not edit.\n";

function assertNoTrailingWhitespace(content, label) {
	const line = content.split("\n").findIndex((value) => /[ \t]+$/.test(value));
	if (line >= 0) throw new Error(`${label} contains trailing whitespace on line ${line + 1}`);
}

async function generatedBytes(name) {
	const source = await readFile(join(root, "lib", `${name}.ts`), "utf8");
	// The runtime layout is FLAT: a lib/authority/ source generates
	// runtime/<basename>.mjs; authority-internal imports flatten to match.
	assertNoTrailingWhitespace(source, `lib/${name}.ts`);
	const javascript = stripTypeScriptTypes(source, { mode: "strip" })
		.replace(/\.ts(["'])/g, ".mjs$1")
		.replace(/(\.{1,2}\/)?authority\/([a-z0-9-]+)\.mjs(["\'])/g, "./$2.mjs$3")
		.replace(/\.{2}\/([a-z0-9-]+)\.mjs(["\'])/g, "./$1.mjs$2")
		// strip 模式会把纯类型具名导入擦成空导入（import {} from "..."），
		// 它仍会在运行时加载目标模块——这里整条删除，类型只有 TS 侧需要。
		.replace(/import\s*\{\s*\}\s*from\s*"[^"]+"\s*;/g, "")
		.replace(/[ \t]+$/gm, "")
		.replace(/\s+$/u, "");
	const generated = `${header}${javascript}\n`;
	assertNoTrailingWhitespace(generated, `runtime/${name}.mjs`);
	return generated;
}

async function main() {
	const mode = process.argv[2];
	if ((mode !== "--write" && mode !== "--check") || process.argv.length !== 3) {
		throw new Error("usage: build-runtime-modules.mjs --write|--check");
	}
	// Pi loads these directly as TypeScript. Check syntax without generating
	// another runtime copy or expanding the published module boundary.
	for (const path of ["lib/runtime-metrics-children.ts", "extensions/runtime-metrics.ts"]) {
		const source = await readFile(join(root, path), "utf8");
		assertNoTrailingWhitespace(source, path);
		stripTypeScriptTypes(source, { mode: "strip" });
	}
	const runtime = join(root, "runtime");
	if (mode === "--write") await mkdir(runtime, { recursive: true });
	const drift = [];
	for (const name of sources) {
		const base = name.split("/").pop();
		const destination = join(runtime, `${base}.mjs`);
		const expected = await generatedBytes(name);
		if (mode === "--write") {
			await writeFile(destination, expected, "utf8");
			continue;
		}
		let actual;
		try {
			actual = await readFile(destination, "utf8");
		} catch {
			actual = undefined;
		}
		if (actual !== expected) drift.push(destination);
	}
	if (drift.length > 0) {
		throw new Error(`generated runtime is stale: ${drift.join(", ")}`);
	}
	// 生成后校验：import 改写（.ts→.mjs、拍平 authority/ 前缀）产出的每
	// 个相对 import 必须真实落在 runtime/ 内。未来有人引入指向 lib 根的
	// 值导入时，这里立即报错，而不是让消费者在 import 时收到
	// ERR_MODULE_NOT_FOUND——字节比较与打包对账都拦不住这类漂移。
	for (const name of sources) {
		const base = name.split("/").pop();
		const generated = await readFile(join(root, "runtime", `${base}.mjs`), "utf8");
		for (const specifier of generated.matchAll(/(?:from\s*|import\(\s*)"(\.[^"]+)"/g)) {
			if (!existsSync(join(root, "runtime", specifier[1]))) {
				throw new Error(`runtime/${base}.mjs imports "${specifier[1]}" which does not exist in runtime/`);
			}
		}
	}
	process.stdout.write(`runtime ${mode === "--write" ? "generated" : "matches TypeScript sources"} (${sources.length} generated modules; one-shot metrics sources validated)\n`);
}

main().catch((error) => {
	process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
	process.exitCode = 1;
});
